import math


# 1. Square Root

print(math.sqrt(25))

print()


# 2. Power

print(math.pow(2, 3))

print()


# 3. Ceiling

print(math.ceil(4.2))

print()


# 4. Floor

print(math.floor(4.8))

print()


# 5. Factorial

print(math.factorial(5))

print()


# 6. Absolute Value

print(math.fabs(-10.5))

print()


# 7. GCD

print(math.gcd(12, 18))

print()


# 8. Constants

print(math.pi)

print(math.e)

print()




# 9. Logarithm

print(math.log(10))

print(math.log10(100))

print()


# 10. Trigonometry

angle = math.radians(90)

print(math.sin(angle))

print(math.cos(angle))

print()


# 11. Degrees and Radians

print(math.radians(180))

print(math.degrees(math.pi))

